"""Measure the pre-tokenizer's character classes from the reference (Spec §6).

The byte-level splitting pattern depends on three Unicode classes: letters
(\\p{L}), numbers (\\p{N}, here the characters the digit stage isolates) and
white space (\\s). Rust's standard library has no letter test that matches
\\p{L}, and a Unicode version that differs from the reference's would move
piece boundaries silently. So instead of trusting either, every Unicode scalar
value is run through the reference's own pre-tokenizer and the classes are
read off its behaviour. The result is committed as Rust source.

usage: uv run python unicode_classes.py
"""

import sys
from importlib.metadata import version
from pathlib import Path

from tokenizers import Tokenizer

from download import MODEL_DIR

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "oxygen" / "src" / "tokenizer" / "unicode_classes.rs"


def classify(pre, c: str) -> str:
    """letter, number, space or other, from how the reference splits strings around c."""
    around = [p for p, _ in pre.pre_tokenize_str("a" + c + " ")]
    # A letter joins the preceding "a" into one piece; a space and its trailing
    # space become one run; anything else leaves c as a piece of its own.
    if len(around) == 2 and around[0] != "a":
        return "letter"
    twice = [p for p, _ in pre.pre_tokenize_str(c + c)]
    if len(twice) == 2:
        return "number"  # the digit stage isolates every number character
    if len(around) == 2:
        return "space"
    return "other"


def ranges(points: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for p in points:
        if out and out[-1][1] + 1 == p:
            out[-1] = (out[-1][0], p)
        else:
            out.append((p, p))
    return out


def main() -> int:
    path = MODEL_DIR / "tokenizer.json"
    if not path.exists():
        print(f"error: {path} is missing; run `uv run python download.py`", file=sys.stderr)
        return 1
    pre = Tokenizer.from_file(str(path)).pre_tokenizer

    classes: dict[str, list[int]] = {"letter": [], "number": [], "space": []}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        kind = classify(pre, chr(cp))
        if kind in classes:
            classes[kind].append(cp)

    lines = [
        "// Generated by oracle/unicode_classes.py: do not edit by hand.",
        f"// Measured from the reference pre-tokenizer (tokenizers {version('tokenizers')}) over every",
        "// Unicode scalar value. Inclusive code point ranges, sorted.",
        "",
    ]
    for kind, name in [("letter", "LETTERS"), ("number", "NUMBERS"), ("space", "SPACES")]:
        rs = ranges(classes[kind])
        lines.append(f"pub(super) const {name}: &[(u32, u32)] = &[")
        for a, b in rs:
            lines.append(f"    (0x{a:04X}, 0x{b:04X}),")
        lines.append("];")
        lines.append("")
        print(f"{kind}: {len(classes[kind])} characters in {len(rs)} ranges")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
